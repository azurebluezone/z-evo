async def synthesize(text: str, voice: str, rate: str, out: Path) -> None:
    out.parent.mkdir(parents=True, exist_ok=True)
    communicate = edge_tts.Communicate(text, voice, rate=rate)
    await communicate.save(str(out))


def audio_seconds(path: Path) -> float | None:
    try:
        result = subprocess.run(
            [
                "ffprobe",
                "-v", "error",
                "-show_entries", "format=duration",
                "-of", "csv=p=0",
                str(path),
            ],
            capture_output=True,
            text=True,
            check=True,
        )
        return float(result.stdout.strip())
    except (OSError, ValueError, subprocess.CalledProcessError):
        return None


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out", type=Path, default=DEFAULT_OUT)
    parser.add_argument("--voice", default=DEFAULT_VOICE)
    parser.add_argument("--rate", default="+0%")
    parser.add_argument("--text-file", type=Path)
    args = parser.parse_args()

    text = args.text_file.read_text(encoding="utf-8").strip() if args.text_file else SCRIPT
    if not text:
        print("No text to synthesize", file=sys.stderr)
        return 2

    asyncio.run(synthesize(text, args.voice, args.rate, args.out))

    seconds = audio_seconds(args.out)
    print(f"WROTE {args.out}")
    print(f"BYTES {args.out.stat().st_size}")
    print(f"SECONDS {seconds if seconds is not None else 'unknown'}")
    print(f"CHARS {len(text)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
