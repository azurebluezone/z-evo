<?php

/**
 * Project image inventory.
 *
 * Usage: php tools/image_inventory.php
 *
 * Scans the two template asset trees, the user-upload tree and the tracked
 * branding filebox; writes docs/image-inventory.json and a readable Markdown
 * table. No Laravel boot and no network: it only reads local files.
 */

$root = dirname(__DIR__);
$directories = [
    'public/admin/assets/img' => 'Admin template (vertical-menu-template) images',
    'public/frontend/landing/pictures' => 'Landing template images (shared + generated)',
    'public/uploads' => 'User uploads referenced by database rows',
    'public/branding' => 'Tracked branding filebox',
];

$extensions = ['jpg', 'jpeg', 'png', 'webp', 'gif', 'svg', 'avif', 'bmp', 'ico'];

function humanBytes(int $bytes): string
{
    if ($bytes >= 1048576) {
        return number_format($bytes / 1048576, 2) . ' MB';
    }
    if ($bytes >= 1024) {
        return number_format($bytes / 1024, 1) . ' KB';
    }
    return $bytes . ' B';
}

function scanImages(string $absoluteDir, array $extensions): array
{
    if (!is_dir($absoluteDir)) {
        return [];
    }

    $images = [];
    $iterator = new RecursiveIteratorIterator(
        new RecursiveDirectoryIterator($absoluteDir, FilesystemIterator::SKIP_DOTS)
    );

    foreach ($iterator as $file) {
        if (!$file->isFile()) {
            continue;
        }

        $extension = strtolower($file->getExtension());
        if (!in_array($extension, $extensions, true)) {
            continue;
        }

        $absolute = $file->getPathname();
        $bytes = (int) $file->getSize();
        $entry = [
            'bytes' => $bytes,
            'format' => strtoupper($extension === 'jpeg' ? 'jpg' : $extension),
        ];

        if ($extension !== 'svg') {
            $size = @getimagesize($absolute);
            if (is_array($size)) {
                $entry['width'] = (int) $size[0];
                $entry['height'] = (int) $size[1];
                $entry['format'] = strtoupper((string) preg_replace('~^IMAGETYPE_~', '', (string) image_type_to_extension($size[2], false)));
            }
        }

        $entry['sha256'] = hash_file('sha256', $absolute) ?: '';
        $images[$absolute] = $entry;
    }

    ksort($images);

    return $images;
}

$report = [
    'generated_at' => date('Y-m-d'),
    'root' => $root,
    'directories' => [],
    'totals' => ['count' => 0, 'bytes' => 0],
];

foreach ($directories as $relativeDir => $label) {
    $absoluteDir = $root . '/' . $relativeDir;
    $images = scanImages($absoluteDir, $extensions);

    $rows = [];
    $totalBytes = 0;
    foreach ($images as $absolute => $entry) {
        $totalBytes += $entry['bytes'];
        $rows[] = array_merge([
            'path' => ltrim(str_replace($root, '', $absolute), '/'),
        ], $entry);
    }

    $report['directories'][$relativeDir] = [
        'label' => $label,
        'count' => count($rows),
        'bytes' => $totalBytes,
        'images' => $rows,
    ];
    $report['totals']['count'] += count($rows);
    $report['totals']['bytes'] += $totalBytes;
}

$jsonPath = $root . '/docs/image-inventory.json';
file_put_contents($jsonPath, json_encode($report, JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES | JSON_UNESCAPED_UNICODE) . "\n");

$lines = [];
$lines[] = '# Project image inventory — 2026-11-12';
$lines[] = '';
$lines[] = 'Generated by `php tools/image_inventory.php`. Covers both template sets (admin vertical-menu assets and landing-template assets), the user-upload tree used by database image columns, and the tracked branding filebox.';
$lines[] = '';
$lines[] = '| Directory | Purpose | Images | Size |';
$lines[] = '| --- | --- | ---: | ---: |';
foreach ($report['directories'] as $relativeDir => $directory) {
    $lines[] = '| `' . $relativeDir . '` | ' . $directory['label'] . ' | ' . $directory['count'] . ' | ' . humanBytes($directory['bytes']) . ' |';
}
$lines[] = '| **Total** | | **' . $report['totals']['count'] . '** | **' . humanBytes($report['totals']['bytes']) . '** |';
$lines[] = '';

foreach ($report['directories'] as $relativeDir => $directory) {
    $lines[] = '## ' . $directory['label'];
    $lines[] = '';
    $lines[] = '`' . $relativeDir . '` — ' . $directory['count'] . ' images, ' . humanBytes($directory['bytes']) . '.';
    $lines[] = '';
    $lines[] = '| Path | Bytes | Size | SHA-256 (first 12) |';
    $lines[] = '| --- | ---: | --- | --- |';

    foreach ($directory['images'] as $image) {
        $dimensions = isset($image['width'], $image['height'])
            ? $image['width'] . '×' . $image['height']
            : 'vector';
        $lines[] = '| `' . $image['path'] . '` | ' . number_format($image['bytes']) . ' | ' . $dimensions . ' | `' . substr($image['sha256'], 0, 12) . '` |';
    }

    $lines[] = '';
}

$lines[] = '## Branding filebox';
$lines[] = '';
$manifestPath = $root . '/public/branding/manifest.json';
if (is_file($manifestPath)) {
    $manifest = json_decode((string) file_get_contents($manifestPath), true) ?: [];
    $lines[] = 'Source: `work/zevo/` (gitignored). Tracked copy and roles:';
    $lines[] = '';
    $lines[] = '| File | Role | Size | Dimensions / duration |';
    $lines[] = '| --- | --- | ---: | --- |';
    foreach ((array) ($manifest['files'] ?? []) as $file) {
        $size = isset($file['width'], $file['height'])
            ? $file['width'] . '×' . $file['height']
            : (isset($file['duration_seconds']) ? $file['duration_seconds'] . ' s' : '—');
        $lines[] = '| `' . $file['path'] . '` | ' . $file['role'] . ' | ' . humanBytes((int) $file['bytes']) . ' | ' . $size . ' |';
    }
    $lines[] = '';
    $lines[] = 'Machine-readable manifest: `public/branding/manifest.json`.';
} else {
    $lines[] = 'Manifest missing: run the branding copy step.';
}
$lines[] = '';
$lines[] = 'Machine-readable inventory: `docs/image-inventory.json`.';
$lines[] = '';

file_put_contents($root . '/docs/IMAGE-INVENTORY-2026-11-12.md', implode("\n", $lines) . "\n");

printf(
    "IMAGE_INVENTORY_OK dirs=%d images=%d bytes=%d\njson=%s\nmarkdown=%s\n",
    count($report['directories']),
    $report['totals']['count'],
    $report['totals']['bytes'],
    $jsonPath,
    $root . '/docs/IMAGE-INVENTORY-2026-11-12.md'
);
